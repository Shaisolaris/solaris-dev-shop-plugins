#!/usr/bin/env python3
"""Verify the generated plugin against its pinned upstream Git revision."""
import argparse
import hashlib
import io
import importlib.util
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tarfile
import tempfile
from urllib.parse import urlsplit

import yaml


def sha(data):
    return hashlib.sha256(data).hexdigest()


def read_source(path):
    head = subprocess.check_output(["git", "-C", str(path), "rev-parse", "HEAD"], text=True).strip()
    raw = subprocess.check_output(["git", "-C", str(path), "archive", "--format=tar", head])
    result = {}
    with tarfile.open(fileobj=io.BytesIO(raw)) as archive:
        for entry in archive:
            if entry.isdir():
                continue
            assert entry.isfile(), "non-regular upstream source: " + entry.name
            result[entry.name] = archive.extractfile(entry).read()
    return head, result


PACKAGER_COMMIT = "129781961be54cc2f12d6bafe80e81d6a1cd8d02"


def listing_metadata(portable):
    interface = portable["extensions"]["com.openai"]["interface"]
    subtitle = interface["shortDescription"]
    assert isinstance(subtitle, str) and 0 < len(subtitle) <= 30
    assert "\n" not in subtitle and "\r" not in subtitle
    terms = interface.get("termsOfServiceURL")
    assert isinstance(terms, str) and terms, "missing software terms URL"
    url = urlsplit(terms)
    assert url.scheme == "https" and url.hostname and not url.username and not url.password


def fresh_coordinator_caller(package):
    skill = package / "skills/chief-of-staff/SKILL.md"
    link = re.search(r"\[routing engine\]\(([^)]+)\)", skill.read_text())
    assert link, "native coordinator has no resolvable engine entrypoint"
    engine = (skill.parent / link.group(1)).resolve()
    assert engine.is_relative_to(package.resolve()) and engine.is_file()
    # The canonical role folder is deliberately not the plugin root. Resolve
    # the entrypoint from the native skill, as its instructions now require.
    run = subprocess.run(
        [sys.executable, "-B", str(engine), "intake", "review this code", "--json"],
        cwd=package / "chief-of-staff", capture_output=True, text=True, timeout=15,
    )
    assert run.returncode == 0, run.stderr
    result = json.loads(run.stdout)
    assert result["decision"] == "assign"
    assert result["assignment"]["primary_capability"] == "solaris.code-reviewer"
    assert result["performed_work"] is False
    return {"result": "PASS", "primary": "solaris.code-reviewer", "performed_work": False}


def rebuild(source_path, packager_path, revision):
    """Rebuild from an immutable reviewed packager, outside the submitted payload."""
    head, trusted = read_source(packager_path)
    assert head == PACKAGER_COMMIT, "unreviewed packager revision"
    for name in ("tools/build_native_plugins.py", "tools/native-plugin-assets/icon.png",
                 "tools/native-plugin-assets/DATA-HANDLING.md"):
        file = packager_path / name
        assert not file.is_symlink() and file.read_bytes() == trusted[name], "dirty packager: " + name
    spec = importlib.util.spec_from_file_location("solaris_reviewed_packager", packager_path / "tools/build_native_plugins.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.git = lambda *args: subprocess.check_output(["git", "-C", str(source_path), *args])
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary) / "rebuilt"
        module.build(revision, output)
        return {str(f.relative_to(output)): (f.read_bytes(), bool(f.stat().st_mode & 0o111))
                for f in output.rglob("*") if f.is_file() and f.suffix != ".zip"}


def validate(root, revision, source, generated):
    # Bind every generated byte, complete catalog and executable mode to the reviewed builder.
    # A manifest supplied alongside a changed payload is not an independent trust anchor.
    for name, (data, executable) in generated.items():
        file = root / name
        assert file.is_file() and not file.is_symlink(), "missing/non-regular generated file: " + name
        assert file.read_bytes() == data, "changed generated file: " + name
        assert bool(file.stat().st_mode & 0o111) == executable, "changed executable mode: " + name
    package = root / "plugin"
    build = json.loads((root / "BUILD.json").read_text())
    provenance = json.loads((package / "SOLARIS-BUILD-SOURCE.json").read_text())
    assert build["source_commit"] == provenance["source_commit"] == revision, "revision mismatch"
    assert provenance["source_path_map"] == {"README.md": "SOURCE-README.md"}
    assert provenance["omitted_repository_config"] == [".gitignore"]
    expected = {provenance["source_path_map"].get(name, name): sha(data)
                for name, data in source.items() if name != ".gitignore"}
    assert provenance["canonical_files"] == expected, "source manifest mismatch"
    for name, digest in expected.items():
        file = package / name
        assert file.is_file() and not file.is_symlink(), "missing/non-regular source: " + name
        assert sha(file.read_bytes()) == digest, "changed source: " + name
    paths = ["chief-of-staff/SKILL.md"] + sorted(name for name in source
             if re.fullmatch(r"employees/[^/]+/[^/]+/SKILL.md", name))
    assert len(paths) == 62, "original role roster changed"
    index = json.loads((package / "native/skills.json").read_text())
    expected_skills = []
    for path in paths:
        metadata = yaml.safe_load(source[path].decode().split("---", 2)[1])
        expected_skills.append({"name": metadata["name"], "description": metadata["description"], "canonical": path})
    assert index == expected_skills, "workflow index differs from source"
    assert len({skill["name"] for skill in index}) == 62
    extra = {"README.md", "DATA-HANDLING.md", "assets/native-plugin-icon.png", "plugin.json",
             ".claude-plugin/plugin.json", "package.json", "native/skills.json", "native/opencode.mjs",
             "server.mjs", "SOLARIS-BUILD-SOURCE.json"}
    for skill in index:
        relative = "skills/" + skill["name"] + "/SKILL.md"
        extra.add(relative)
        file = package / relative
        text = file.read_text()
        metadata = yaml.safe_load(text.split("---", 2)[1])
        assert metadata == {"name": skill["name"], "description": skill["description"]}
        link = "../../" + skill["canonical"]
        assert "](" + link + ")" in text
        assert (file.parent / link).resolve() == (package / skill["canonical"]).resolve()
    actual = set()
    for file in package.rglob("*"):
        assert not file.is_symlink(), "symlink in plugin"
        if file.is_file():
            actual.add(str(file.relative_to(package)))
    assert actual == set(expected) | extra, "unexpected or missing package files"
    portable = json.loads((package / "plugin.json").read_text())
    listing_metadata(portable)
    claude = json.loads((package / ".claude-plugin/plugin.json").read_text())
    node = json.loads((package / "package.json").read_text())
    assert portable["version"] == claude["version"] == node["version"] == build["plugin_version"]
    assert portable["name"] == claude["name"] == "solaris-dev-shop"
    assert portable["extensions"]["com.openai"]["requires_local_executor"] is True
    assert portable["author"]["name"] == claude["author"]["name"] == "Solaris Technologies"
    assert "mcpServers" not in claude and "hooks" not in claude
    assert node["dependencies"] == {"@opencode/plugin": "2.1.2"}
    icon = (package / "assets/native-plugin-icon.png").read_bytes()
    assert icon[:8] == b"\x89PNG\r\n\x1a\n"
    width, height = struct.unpack(">II", icon[16:24])
    assert width == height and 512 <= width <= 2048 and len(icon) < 2 * 1024 * 1024
    assert sha(icon) == provenance["listing_icon_sha256"]
    openai_catalog = json.loads((root / ".agents/plugins/marketplace.json").read_text())
    claude_catalog = json.loads((root / ".claude-plugin/marketplace.json").read_text())
    assert openai_catalog["name"] == claude_catalog["name"] == "solaris-technologies"
    assert openai_catalog["plugins"][0]["source"]["path"] == claude_catalog["plugins"][0]["source"] == "./plugin"
    for folder in [root, package]:
        for link in re.findall(r"\]\(([^)]+)\)", (folder / "README.md").read_text()):
            if not link.startswith(("https:", "#")):
                assert (folder / link).is_file(), "broken README link: " + link
    return {"source_commit": revision, "canonical_files": len(expected), "workflows": len(index),
            "native_formats": 3, "icon_dimensions": [width, height], "result": "PASS"}


def controls(root, revision, source, generated):
    with tempfile.TemporaryDirectory() as temporary:
        copy = Path(temporary) / "distribution"
        shutil.copytree(root, copy, ignore=shutil.ignore_patterns(".git", "__pycache__", "node_modules"))
        probes = [
            ("changed helper", "plugin/employees/product-project/delivery-lead/delivery_evidence.py", b"print('stub')\n"),
            ("missing workflow", "plugin/skills/backend-developer/SKILL.md", None),
            ("dropped workflow index", "plugin/native/skills.json", b"[]\n"),
            ("unbound revision", "BUILD.json", json.dumps(dict(json.loads((copy / "BUILD.json").read_text()), source_commit="0" * 40)).encode()),
        ]
        node = json.loads((copy / "plugin/package.json").read_text())
        node["scripts"] = {"postinstall": "node -e \"console.log('synthetic sentinel')\""}
        catalog = json.loads((copy / ".claude-plugin/marketplace.json").read_text())
        catalog["plugins"].append({"name": "unreviewed", "source": "../../outside"})
        adapter = (copy / "plugin/skills/backend-developer/SKILL.md").read_bytes()
        probes.extend([
            ("changed native loader", "plugin/server.mjs", b"export default {};\n"),
            ("changed native implementation", "plugin/native/opencode.mjs", b"export default {};\n"),
            ("added lifecycle script", "plugin/package.json", json.dumps(node).encode()),
            ("injected adapter instructions", "plugin/skills/backend-developer/SKILL.md", adapter + b"\nSynthetic unreviewed instruction.\n"),
            ("extra marketplace entry", ".claude-plugin/marketplace.json", json.dumps(catalog).encode()),
        ])
        rejected = []
        for label, name, replacement in probes:
            file = copy / name
            original = file.read_bytes()
            if replacement is None:
                file.unlink()
            else:
                file.write_bytes(replacement)
            try:
                validate(copy, revision, source, generated)
            except (AssertionError, OSError, ValueError, KeyError):
                rejected.append(label)
            finally:
                file.write_bytes(original)
            assert label in rejected, "negative control falsely accepted: " + label
        return rejected


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--packager", required=True, type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    revision, files = read_source(args.source)
    generated = rebuild(args.source.resolve(), args.packager.resolve(), revision)
    result = validate(root, revision, files, generated)
    if args.self_test:
        result["rejected_controls"] = controls(root, revision, files, generated)
        result["fresh_coordinator_caller"] = fresh_coordinator_caller(root / "plugin")
        portable = json.loads((root / "plugin/plugin.json").read_text())
        listing_rejected = []
        for label in ["overlong subtitle", "missing terms"]:
            bad = json.loads(json.dumps(portable))
            interface = bad["extensions"]["com.openai"]["interface"]
            if label == "overlong subtitle":
                interface["shortDescription"] = "x" * 31
            else:
                interface.pop("termsOfServiceURL")
            try:
                listing_metadata(bad)
            except AssertionError:
                listing_rejected.append(label)
            assert label in listing_rejected, "listing regression accepted: " + label
        result["rejected_listing_controls"] = listing_rejected
    print(json.dumps(result, indent=2))
